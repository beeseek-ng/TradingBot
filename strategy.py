# 2. Key Level & Imbalance Detector
# ---------------------------------------------------------------------------
class KeyLevelDetector:
    """
    Identifies A-shape key levels (resistance), V-shape key levels (support),
    Open/Close levels, Fair Value Gaps (FVG), and Order Blocks (OB).
    """

    @staticmethod
    def find_a_shape_levels(df: pd.DataFrame, lookback: int = 30) -> List[KeyLevel]:
        """
        Finds A-shape resistance peaks that sponsored sells multiple times.
        """
        levels: List[KeyLevel] = []
        if len(df) < lookback:
            return levels

        sub_df = df.iloc[-lookback:].copy()
        highs = sub_df["high"].values
        lows = sub_df["low"].values
        times = sub_df["time"].values if "time" in sub_df.columns else sub_df.index.values

        for i in range(2, len(sub_df) - 2):
            if highs[i] >= highs[i-1] and highs[i] >= highs[i-2] and highs[i] >= highs[i+1] and highs[i] >= highs[i+2]:
                peak_price = highs[i]
                # Count how many subsequent bars tested this peak area (within 0.05% tolerance)
                tolerance = peak_price * 0.0008
                touches = 1
                disrespected = False
                disrespected_time = None

                for k in range(i + 1, len(sub_df)):
                    if abs(highs[k] - peak_price) <= tolerance:
                        touches += 1
                    if sub_df["close"].values[k] > peak_price + tolerance:
                        disrespected = True
                        disrespected_time = times[k]
                        break

                levels.append(KeyLevel(
                    level_type=KeyLevelType.A_SHAPE_RESISTANCE,
                    price=peak_price,
                    high_boundary=peak_price + tolerance,
                    low_boundary=peak_price - tolerance,
                    timestamp=times[i],
                    touches=touches,
                    is_disrespected=disrespected,
                    disrespected_time=disrespected_time
                ))
        return levels

    @staticmethod
    def find_v_shape_levels(df: pd.DataFrame, lookback: int = 30) -> List[KeyLevel]:
        """
        Finds V-shape support valleys that sponsored buys multiple times.
        """
        levels: List[KeyLevel] = []
        if len(df) < lookback:
            return levels

        sub_df = df.iloc[-lookback:].copy()
        highs = sub_df["high"].values
        lows = sub_df["low"].values
        times = sub_df["time"].values if "time" in sub_df.columns else sub_df.index.values

        for i in range(2, len(sub_df) - 2):
            if lows[i] <= lows[i-1] and lows[i] <= lows[i-2] and lows[i] <= lows[i+1] and lows[i] <= lows[i+2]:
                valley_price = lows[i]
                tolerance = valley_price * 0.0008
                touches = 1
                disrespected = False
                disrespected_time = None

                for k in range(i + 1, len(sub_df)):
                    if abs(lows[k] - valley_price) <= tolerance:
                        touches += 1
                    if sub_df["close"].values[k] < valley_price - tolerance:
                        disrespected = True
                        disrespected_time = times[k]
                        break

                levels.append(KeyLevel(
                    level_type=KeyLevelType.V_SHAPE_SUPPORT,
                    price=valley_price,
                    high_boundary=valley_price + tolerance,
                    low_boundary=valley_price - tolerance,
                    timestamp=times[i],
                    touches=touches,
                    is_disrespected=disrespected,
                    disrespected_time=disrespected_time
                ))
        return levels

    @staticmethod
    def find_fair_value_gaps(df: pd.DataFrame, min_pips: float, spec: SymbolSpec, lookback: int = 25) -> List[KeyLevel]:
        """
        Identifies Fair Value Gaps (3-candle imbalance).
        - Bullish FVG: Low[i] > High[i-2]
        - Bearish FVG: High[i] < Low[i-2]
        """
        fvgs: List[KeyLevel] = []
        if len(df) < 3:
            return fvgs

        sub_df = df.iloc[-lookback:].copy()
        highs = sub_df["high"].values
        lows = sub_df["low"].values
        times = sub_df["time"].values if "time" in sub_df.columns else sub_df.index.values
        min_delta = spec.pips_to_price_delta(min_pips)

        for i in range(2, len(sub_df)):
            # Bullish FVG
            if lows[i] > highs[i-2] + min_delta:
                fvgs.append(KeyLevel(
                    level_type=KeyLevelType.FAIR_VALUE_GAP,
                    price=(lows[i] + highs[i-2]) / 2.0,
                    high_boundary=lows[i],
                    low_boundary=highs[i-2],
                    timestamp=times[i-1]
                ))
            # Bearish FVG
            elif highs[i] < lows[i-2] - min_delta:
                fvgs.append(KeyLevel(
                    level_type=KeyLevelType.FAIR_VALUE_GAP,
                    price=(highs[i] + lows[i-2]) / 2.0,
                    high_boundary=lows[i-2],
                    low_boundary=highs[i],
                    timestamp=times[i-1]
                ))
        return fvgs


