# 1. Market Environment & Phase Classifier
# ---------------------------------------------------------------------------
class MarketEnvironmentClassifier:
    """
    Classifies market structure into Uptrend, Downtrend, Ranging, or Choppy,
    and identifies Expansion vs Reversal phases.
    """

    @staticmethod
    def classify(df: pd.DataFrame, lookback: int = 20) -> Tuple[MarketEnvironment, MarketPhase]:
        """
        Analyzes swing points, candle overlap, and momentum expansion.
        """
        if len(df) < lookback + 5:
            return MarketEnvironment.CHOPPY, MarketPhase.CONSOLIDATION

        recent = df.iloc[-lookback:].copy()
        highs = recent["high"].values
        lows = recent["low"].values
        opens = recent["open"].values
        closes = recent["close"].values

        # 1. Swing Highs & Lows detection
        swing_highs = []
        swing_lows = []
        for j in range(2, len(recent) - 2):
            if highs[j] > highs[j-1] and highs[j] > highs[j-2] and highs[j] > highs[j+1] and highs[j] > highs[j+2]:
                swing_highs.append(highs[j])
            if lows[j] < lows[j-1] and lows[j] < lows[j-2] and lows[j] < lows[j+1] and lows[j] < lows[j+2]:
                swing_lows.append(lows[j])

        # 2. Check Trend Direction (HH/HL vs LH/LL)
        is_uptrend = False
        is_downtrend = False

        if len(swing_highs) >= 2 and len(swing_lows) >= 2:
            hh = swing_highs[-1] > swing_highs[-2]
            hl = swing_lows[-1] > swing_lows[-2]
            lh = swing_highs[-1] < swing_highs[-2]
            ll = swing_lows[-1] < swing_lows[-2]

            if hh and hl:
                is_uptrend = True
            elif lh and ll:
                is_downtrend = True

        # 3. Check for Choppiness / Body Overlap
        candle_ranges = highs - lows
        avg_range = np.mean(candle_ranges) if len(candle_ranges) > 0 else 1e-5
        body_sizes = np.abs(closes - opens)
        avg_body = np.mean(body_sizes) if len(body_sizes) > 0 else 1e-5
        
        # Heavy wick / small body overlap indicates chop
        body_to_range_ratio = avg_body / avg_range if avg_range > 0 else 0

        # 4. Check for Expansion vs Reversal
        latest_candle_range = highs[-1] - lows[-1]
        latest_body = abs(closes[-1] - opens[-1])
        latest_expansion = (latest_body / latest_candle_range) >= 0.60 if latest_candle_range > 0 else False

        if is_uptrend:
            env = MarketEnvironment.UPTREND
            phase = MarketPhase.EXPANSION if (closes[-1] > opens[-1] and latest_expansion) else MarketPhase.CONSOLIDATION
        elif is_downtrend:
            env = MarketEnvironment.DOWNTREND
            phase = MarketPhase.EXPANSION if (closes[-1] < opens[-1] and latest_expansion) else MarketPhase.CONSOLIDATION
        elif body_to_range_ratio < 0.35:
            env = MarketEnvironment.CHOPPY
            phase = MarketPhase.CONSOLIDATION
        else:
            env = MarketEnvironment.RANGING
            phase = MarketPhase.CONSOLIDATION

        # Reversal detection: Latest candle swept a swing extreme and reversed
        if len(swing_highs) > 0 and highs[-1] > swing_highs[-1] and closes[-1] < opens[-1]:
            phase = MarketPhase.REVERSAL
        elif len(swing_lows) > 0 and lows[-1] < swing_lows[-1] and closes[-1] > opens[-1]:
            phase = MarketPhase.REVERSAL

        return env, phase


