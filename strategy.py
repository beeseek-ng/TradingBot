"""
ForexBot Strategy Engine (SLK + CRT + ABC/XYZ Multi-Timeframe Framework)
========================================================================
Institutional Price Action & Market Storyline Signal Generation Engine:
1. SLK (Structure, Liquidity, Key Level):
   - Market Environment: UPTREND, DOWNTREND, RANGING, CHOPPY
   - Market Phase: EXPANSION vs REVERSAL
   - Origin & Destination: Where price is coming from -> Where price is going
2. CRT (Candle Range Theory):
   - Candle High/Low sweep with candle closing back inside the range.
   - 3rd candle reaction from Key Levels (Open/Close, V-Shape, A-Shape, FVG, OB).
3. ABC (HTF Expectation) -> XYZ (LTF Execution):
   - HTF (Weekly / Daily / 4H / 2H) bias & liquidity sweep + breakout.
   - LTF (2H / 1H / 15M) London & New York session execution on disrespected
     key level flip into Imbalance (FVG) + Liquidity Sweep confirmation.
4. Risk/Reward:
   - Fixed Stop Loss: 50.0 pips
   - Fixed Take Profit: 150.0 pips (TP1) / 250.0 pips (TP2)
"""

from dataclasses import dataclass, field
from enum import Enum
from typing import Optional, Dict, Any, List, Tuple
import numpy as np
import pandas as pd

from config import (
    SUPPORTED_SYMBOLS,
    StrategyConfig,
    SessionConfig,
    SymbolSpec,
)


class SignalType(str, Enum):
    """Explicit trade action signal."""
    BUY = "BUY"
    SELL = "SELL"
    HOLD = "HOLD"


class MarketEnvironment(str, Enum):
    """Market structure regime."""
    UPTREND = "UPTREND"
    DOWNTREND = "DOWNTREND"
    RANGING = "RANGING"
    CHOPPY = "CHOPPY"


class MarketPhase(str, Enum):
    """Current price delivery phase."""
    EXPANSION = "EXPANSION"
    REVERSAL = "REVERSAL"
    CONSOLIDATION = "CONSOLIDATION"


class KeyLevelType(str, Enum):
    """Types of identified key price levels."""
    A_SHAPE_RESISTANCE = "A_SHAPE_RESISTANCE"  # Swing High / Resistance peak
    V_SHAPE_SUPPORT = "V_SHAPE_SUPPORT"        # Swing Low / Support valley
    OPEN_CLOSE_LEVEL = "OPEN_CLOSE_LEVEL"      # Horizontal Open/Close cluster
    FAIR_VALUE_GAP = "FAIR_VALUE_GAP"          # 3-candle imbalance (FVG)
    ORDER_BLOCK = "ORDER_BLOCK"                # Last opposing candle before displacement


@dataclass
class KeyLevel:
    """Represents a structural price key level."""
    level_type: KeyLevelType
    price: float
    high_boundary: float
    low_boundary: float
    timestamp: Any
    touches: int = 1
    is_disrespected: bool = False
    disrespected_time: Optional[Any] = None
    timeframe: str = "15m"


@dataclass
class CRTSweep:
    """Candle Range Theory (CRT) sweep event."""
    is_bullish_sweep: bool     # Swept low and closed back up inside range
    is_bearish_sweep: bool     # Swept high and closed back down inside range
    swept_level: float
    candle_time: Any
    timeframe: str
    target_liquidity: float


@dataclass
class MarketStoryline:
    """Complete multi-timeframe market state."""
    environment: MarketEnvironment
    phase: MarketPhase
    origin_liquidity: str      # Where price is coming from
    destination_liquidity: str # Where price is likely going next
    htf_bias: SignalType       # Expected directional bias (BUY / SELL / HOLD)
    rationale: str


@dataclass
class TradeSignal:
    """
    Structured container for trade signals generated by the strategy engine.
    """
    symbol: str
    signal: SignalType
    timestamp: Any
    entry_price: float
    stop_loss: float
    take_profit: float
    sl_pips: float
    tp_pips: float
    tp2_price: float
    tp2_pips: float
    lot_size: float
    rationale: str
    storyline: Optional[MarketStoryline] = None
    metadata: Dict[str, Any] = field(default_factory=dict)

    @property
    def is_actionable(self) -> bool:
        """Returns True if signal is BUY or SELL."""
        return self.signal in (SignalType.BUY, SignalType.SELL)


